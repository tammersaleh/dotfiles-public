local h = require('helpers')

describe("surround", function()
  before_each(function()
    vim.cmd("doautocmd User VeryLazy")
    h.set_buf({ "foo bar baz" })
    h.set_cursor(1, 5)
  end)

  for open, close in pairs({ ["("] = ")", ["["] = "]", ["{"] = "}", ["<"] = ">" }) do
    it("ysiw" .. open .. " adds no padding", function()
      h.feed("ysiw" .. open)
      assert.are.same({ "foo " .. open .. "bar" .. close .. " baz" }, h.get_buf())
    end)
  end
end)

describe("surround gv", function()
  before_each(function()
    vim.cmd("doautocmd User VeryLazy")
    h.set_buf({ "foo bar baz" })
    h.set_cursor(1, 5)
  end)

  it("reselects the surrounded word after viwS*", function()
    h.feed("viwS*")
    assert.are.same({ "foo *bar* baz" }, h.get_buf())
    h.feed("gv")
    assert.equals("v", h.get_mode())
    local s = vim.fn.getpos("v")
    local e = vim.fn.getpos(".")
    h.ensure_normal()
    assert.are.same({ 6, 8 }, { math.min(s[3], e[3]), math.max(s[3], e[3]) })
  end)

  it("reselects the surrounded line after VS*", function()
    h.set_buf({ "one", "foo bar baz", "two" })
    h.set_cursor(2, 5)
    h.feed("VS*")
    assert.are.same({ "one", "*", "foo bar baz", "*", "two" }, h.get_buf())
    h.feed("gv")
    assert.equals("V", h.get_mode())
    local s = vim.fn.getpos("v")
    local e = vim.fn.getpos(".")
    h.ensure_normal()
    assert.are.same({ 3, 3 }, { s[2], e[2] })
  end)
end)

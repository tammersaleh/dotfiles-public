local h = require('helpers')

describe("markdown mappings (with plugins)", function()
  before_each(function()
    h.reset()
    vim.bo.filetype = 'markdown'
  end)

  it("leaves the indent operators alone", function()
    assert.equals('', vim.fn.maparg('>>', 'n'))
    assert.equals('', vim.fn.maparg('<<', 'n'))
    assert.equals('', vim.fn.maparg('<C-t>', 'i'))
    assert.equals('', vim.fn.maparg('<C-d>', 'i'))
  end)

  it("keeps the list mappings we use", function()
    h.assert_buf_keymap('i', '<CR>')
    h.assert_buf_keymap('n', 'o')
    h.assert_buf_keymap('n', ' x')
  end)

  describe("<CR> next to cmp", function()
    it("is the buffer's <CR>", function()
      local map = h.assert_buf_keymap('i', '<CR>')
      assert.equals('<C-]><Plug>(config-lists-newline)', map.rhs)
    end)

    it("splits an item once cmp has wrapped the mapping", function()
      h.set_buf({ "- one two" })
      h.set_cursor(1, 5)
      h.feed("i<CR>") -- InsertEnter: cmp installs its own <CR> with ours as the fallback
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
      h.set_buf({ "- one two" })
      h.set_cursor(1, 5)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)
  end)

  describe("<leader>x", function()
    it("toggles a checkbox", function()
      h.set_buf({ "- [ ] task" })
      h.set_cursor(1)
      h.feed("<leader>x")
      assert.are.same({ "- [x] task" }, h.get_buf())
      h.feed("<leader>x")
      assert.are.same({ "- [ ] task" }, h.get_buf())
    end)

    it("toggles the parent from a nested item and keeps the cursor", function()
      h.set_buf({ "- [ ] task", "    - sub" })
      h.set_cursor(2, 6)
      h.feed("<leader>x")
      assert.are.same({ "- [x] task", "    - sub" }, h.get_buf())
      assert.are.same({ 2, 6 }, h.get_cursor())
    end)

    it("does nothing without a checkbox target", function()
      h.set_buf({ "- [ ] other", "- task", "    - sub" })
      h.set_cursor(3)
      h.feed("<leader>x")
      assert.are.same({ "- [ ] other", "- task", "    - sub" }, h.get_buf())
    end)

    it("leaves link items alone when setting children", function()
      h.set_buf({ "- [ ] task", "    - [Link](http://x)", "    - [ ] sub" })
      h.set_cursor(1)
      h.feed("<leader>x")
      assert.are.same({ "- [x] task", "    - [Link](http://x)", "    - [x] sub" }, h.get_buf())
    end)

    it("repeats with .", function()
      h.set_buf({ "- [ ] a", "- [ ] b", "- [ ] c" })
      h.set_cursor(1)
      h.feed("<leader>x")
      h.feed("j.")
      h.feed("j.")
      assert.are.same({ "- [x] a", "- [x] b", "- [x] c" }, h.get_buf())
      assert.are.same({ 3, 0 }, h.get_cursor())
    end)

    it("does not replace the . command when there is no target", function()
      h.set_buf({ "xx", "para" })
      h.set_cursor(1)
      h.feed("x")
      h.set_cursor(2)
      h.feed("<leader>x")
      h.feed(".")
      assert.are.same({ "x", "ara" }, h.get_buf())
    end)

    it("works at the end of the line", function()
      h.set_buf({ "- [ ] task" })
      h.set_cursor(1, 9)
      h.feed("<leader>x")
      assert.are.same({ "- [x] task" }, h.get_buf())
      assert.are.same({ 1, 9 }, h.get_cursor())
    end)

    it("undoes the whole tree in one step", function()
      h.set_buf({ "- [ ] a", "    - [ ] b", "    - [ ] c" })
      vim.bo.undolevels = vim.bo.undolevels -- the setup write is not part of the test's undo history
      h.set_cursor(1)
      h.feed("<leader>x")
      assert.are.same({ "- [x] a", "    - [x] b", "    - [x] c" }, h.get_buf())
      h.feed("u")
      assert.are.same({ "- [ ] a", "    - [ ] b", "    - [ ] c" }, h.get_buf())
    end)

    it("is not mapped in slack buffers", function()
      vim.bo.filetype = 'slack'
      for _, map in ipairs(vim.api.nvim_buf_get_keymap(0, 'n')) do
        assert.is_not.equal(' x', map.lhs)
      end
    end)

    it("works inside a blockquote", function()
      h.set_buf({ "> - [ ] task", ">     - sub" })
      h.set_cursor(2, 8)
      h.feed("<leader>x")
      assert.are.same({ "> - [x] task", ">     - sub" }, h.get_buf())
      assert.are.same({ 2, 8 }, h.get_cursor())
    end)
  end)

  describe("o", function()
    it("continues a list", function()
      h.set_buf({ "- one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)

    it("continues a quoted list", function()
      h.set_buf({ "> - one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "> - one", "> - two" }, h.get_buf())
    end)

    it("continues a quoted paragraph", function()
      h.set_buf({ "> one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "> one", "> two" }, h.get_buf())
    end)

    it("continues a nested quoted paragraph", function()
      h.set_buf({ "> > one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "> > one", "> > two" }, h.get_buf())
    end)

    it("is a plain new line on a paragraph", function()
      h.set_buf({ "one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "one", "two" }, h.get_buf())
    end)
  end)
end)

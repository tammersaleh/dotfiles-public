local h = require('helpers')

-- Insert-mode <CR> in markdown is lua/config/lists.lua returning keys from an
-- expr mapping, so the whole suite runs without plugins and `.` can be tested.
describe("markdown <CR>", function()
  before_each(function()
    h.reset()
    vim.bo.filetype = 'markdown'
    vim.bo.shiftwidth = 4
    vim.bo.tabstop = 4
    vim.bo.expandtab = true
  end)

  describe("list continuation", function()
    it("continues the bullet at end of line", function()
      h.set_buf({ "- one" })
      h.set_cursor(1, 4)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)

    it("continues the bullet when splitting mid-line", function()
      h.set_buf({ "- one two" })
      h.set_cursor(1, 5)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)

    it("leaves the cursor before the moved text", function()
      h.set_buf({ "- one two" })
      h.set_cursor(1, 5)
      h.feed("i<CR>X")
      h.ensure_normal()
      assert.are.same({ "- one", "- Xtwo" }, h.get_buf())
    end)

    it("splits before the space as well as after it", function()
      h.set_buf({ "- one two" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)

    it("drops several spaces around the split point", function()
      h.set_buf({ "- one   two" })
      h.set_cursor(1, 8)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)

    it("keeps the indent when splitting a nested bullet", function()
      h.set_buf({ "- parent", "    - one two" })
      h.set_cursor(2, 9)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- parent", "    - one", "    - two" }, h.get_buf())
    end)

    it("keeps a tab indent", function()
      vim.bo.expandtab = false
      h.set_buf({ "- parent", "\t- one" })
      h.set_cursor(2, 5)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "- parent", "\t- one", "\t- two" }, h.get_buf())
    end)

    it("continues * and + lists", function()
      h.set_buf({ "* one" })
      h.set_cursor(1, 4)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "* one", "* two" }, h.get_buf())
      h.set_buf({ "+ one" })
      h.set_cursor(1, 4)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "+ one", "+ two" }, h.get_buf())
    end)

    it("keeps trailing spaces at end of line (hard break)", function()
      h.set_buf({ "- one  " })
      h.set_cursor(1, 6)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "- one  ", "- two" }, h.get_buf())
    end)

    it("splits a checkbox item into an unchecked item", function()
      h.set_buf({ "- [x] one two" })
      h.set_cursor(1, 9)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- [x] one", "- [ ] two" }, h.get_buf())
    end)

    it("accepts an uppercase checkbox", function()
      h.set_buf({ "- [X] one" })
      h.set_cursor(1, 8)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "- [X] one", "- [ ] two" }, h.get_buf())
    end)

    it("splits after a multibyte character", function()
      h.set_buf({ "- café résumé" })
      h.set_cursor(1, 8) -- byte offset: "- café " is 8 bytes
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- café", "- résumé" }, h.get_buf())
    end)

    it("types after the new marker", function()
      h.set_buf({ "    - one" })
      h.set_cursor(1, 8)
      h.feed("a<CR>X")
      h.ensure_normal()
      assert.are.same({ "    - one", "    - X" }, h.get_buf())
    end)
  end)

  describe("ordered lists", function()
    it("numbers the new item when splitting an ordered list", function()
      h.set_buf({ "1. one two", "2. three" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two", "3. three" }, h.get_buf())
    end)

    it("renumbers a list that is out of order", function()
      h.set_buf({ "5. one two", "8. three" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two", "3. three" }, h.get_buf())
    end)

    it("continues a ) ordered list", function()
      h.set_buf({ "1) one two" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "1) one", "2) two" }, h.get_buf())
    end)

    it("goes from 9 to 10", function()
      h.set_buf({ "9. one" })
      h.set_cursor(1, 5)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two" }, h.get_buf())
    end)

    it("keeps the cursor before the moved text after renumbering", function()
      h.set_buf({ "99. one two" })
      h.set_cursor(1, 7)
      h.feed("i<CR>X")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. Xtwo" }, h.get_buf())
    end)

    it("stops renumbering at a blank line", function()
      h.set_buf({ "1. one", "", "7. other" })
      h.set_cursor(1, 5)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two", "", "7. other" }, h.get_buf())
    end)

    it("stops renumbering at a paragraph", function()
      h.set_buf({ "1. one", "text", "7. other" })
      h.set_cursor(1, 5)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two", "text", "7. other" }, h.get_buf())
    end)

    it("renumbers items after an indented continuation line", function()
      h.set_buf({ "1. one", "   more", "5. three" })
      h.set_cursor(1, 5)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two", "   more", "3. three" }, h.get_buf())
    end)

    it("renumbers a nested ordered list on its own counter", function()
      h.set_buf({ "5. parent", "    8. child", "    9. child", "9. next" })
      h.set_cursor(1, 8)
      h.feed("a<CR>new")
      h.ensure_normal()
      assert.are.same({ "1. parent", "2. new", "    1. child", "    2. child", "3. next" }, h.get_buf())
    end)

    it("restarts the nested counter after returning to the parent", function()
      h.set_buf({ "1. a", "    1. b", "2. c", "    5. d" })
      h.set_cursor(4, 7)
      h.feed("a<CR>e")
      h.ensure_normal()
      assert.are.same({ "1. a", "    1. b", "2. c", "    1. d", "    2. e" }, h.get_buf())
    end)

    it("leaves unordered items alone while renumbering", function()
      h.set_buf({ "1. one", "    - sub", "5. three" })
      h.set_cursor(1, 5)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. two", "    - sub", "3. three" }, h.get_buf())
    end)

    it("stops at an unordered item at the same level", function()
      h.set_buf({ "5. one", "- unrelated", "8. two" })
      h.set_cursor(1, 5)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. x", "- unrelated", "8. two" }, h.get_buf())
    end)

    it("stops at an ordered item with the other delimiter", function()
      h.set_buf({ "5. one", "8) two" })
      h.set_cursor(1, 5)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. x", "8) two" }, h.get_buf())
    end)

    it("stops the nested list at the next parent item", function()
      h.set_buf({ "- a", "    1. x", "    5. y", "- b", "    7. z" })
      h.set_cursor(3, 7)
      h.feed("a<CR>w")
      h.ensure_normal()
      assert.are.same({ "- a", "    1. x", "    2. y", "    3. w", "- b", "    7. z" }, h.get_buf())
    end)

    it("measures nesting by display width, not bytes", function()
      h.set_buf({ "1. parent", "\t8. child", "    9. sibling" })
      h.set_cursor(1, 8)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "1. parent", "2. x", "\t1. child", "    2. sibling" }, h.get_buf())
    end)

    it("does not renumber a - list", function()
      h.set_buf({ "- one", "- two", "7. stray" })
      h.set_cursor(1, 4)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "- one", "- x", "- two", "7. stray" }, h.get_buf())
    end)

    it("undoes the split and the renumber together", function()
      h.set_buf({ "5. one two", "8. three" })
      vim.cmd('let &undolevels = &undolevels') -- close the undo block set_buf opened
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      h.feed("u")
      assert.are.same({ "5. one two", "8. three" }, h.get_buf())
    end)
  end)

  describe("nesting after a colon", function()
    it("nests the new item when the split leaves a colon at the end", function()
      h.set_buf({ "- head: tail" })
      h.set_cursor(1, 7)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- head:", "    - tail" }, h.get_buf())
    end)

    it("keeps the parent's marker", function()
      h.set_buf({ "* head:" })
      h.set_cursor(1, 6)
      h.feed("a<CR>tail")
      h.ensure_normal()
      assert.are.same({ "* head:", "    * tail" }, h.get_buf())
    end)

    it("restarts a numbered list under the colon", function()
      h.set_buf({ "3. head:" })
      h.set_cursor(1, 7)
      h.feed("a<CR>tail")
      h.ensure_normal()
      assert.are.same({ "1. head:", "    1. tail" }, h.get_buf())
    end)

    it("nests deeper from a nested item", function()
      h.set_buf({ "    - head:" })
      h.set_cursor(1, 10)
      h.feed("a<CR>tail")
      h.ensure_normal()
      assert.are.same({ "    - head:", "        - tail" }, h.get_buf())
    end)

    it("does not nest when only the moved text ends in a colon", function()
      h.set_buf({ "- head tail:" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- head", "- tail:" }, h.get_buf())
    end)
  end)

  describe("plain newlines", function()
    it("treats a split inside the marker padding as a plain newline", function()
      h.set_buf({ "-  one" })
      h.set_cursor(1, 2)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- ", "one" }, h.get_buf())
    end)

    it("treats a split before checkbox text as a plain newline", function()
      h.set_buf({ "- [x] one" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- [x] ", "one" }, h.get_buf())
    end)

    it("splits a plain paragraph without adding a bullet", function()
      h.set_buf({ "one two" })
      h.set_cursor(1, 3)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "one", "two" }, h.get_buf())
    end)

    it("splits before the item text without adding a bullet", function()
      h.set_buf({ "- one" })
      h.set_cursor(1, 2)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "- ", "one" }, h.get_buf())
    end)

    it("leaves headings, fences and table rows alone", function()
      for _, line in ipairs({ "# one", "```lua", "| a | b |" }) do
        h.set_buf({ line })
        h.set_cursor(1, #line - 1)
        h.feed("a<CR>x")
        h.ensure_normal()
        assert.are.same({ line, "x" }, h.get_buf())
      end
    end)

    it("<C-CR> is a plain newline on an item", function()
      h.set_buf({ "- one" })
      h.set_cursor(1, 4)
      h.feed("a<C-CR>two")
      h.ensure_normal()
      assert.are.same({ "- one", "two" }, h.get_buf())
    end)
  end)

  describe("empty items", function()
    it("removes an empty bullet instead of continuing it", function()
      h.set_buf({ "- one", "- " })
      h.set_cursor(2, 1)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "" }, h.get_buf())
    end)

    it("removes an empty nested bullet without touching the line above", function()
      h.set_buf({ "- one", "    - " })
      h.set_cursor(2, 5)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "" }, h.get_buf())
    end)

    it("removes an empty tab-indented bullet", function()
      vim.bo.expandtab = false
      h.set_buf({ "- one", "\t- " })
      h.set_cursor(2, 2)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "- one", "" }, h.get_buf())
    end)

    it("removes an empty numbered item and an empty checkbox", function()
      h.set_buf({ "1. one", "2. " })
      h.set_cursor(2, 2)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "1. one", "" }, h.get_buf())
      h.set_buf({ "- [ ] one", "- [ ] " })
      h.set_cursor(2, 5)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "- [ ] one", "" }, h.get_buf())
    end)

    it("leaves insert mode on the cleared line", function()
      h.set_buf({ "- one", "- " })
      h.set_cursor(2, 1)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "- one", "x" }, h.get_buf())
    end)
  end)

  describe("blockquotes", function()
    it("continues a blockquote at end of line", function()
      h.set_buf({ "> one" })
      h.set_cursor(1, 4)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> one", "> two" }, h.get_buf())
    end)

    it("continues a blockquote when splitting mid-line", function()
      h.set_buf({ "> one two" })
      h.set_cursor(1, 6)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "> one", "> two" }, h.get_buf())
    end)

    it("continues a nested blockquote", function()
      h.set_buf({ "> > one" })
      h.set_cursor(1, 6)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> > one", "> > two" }, h.get_buf())
    end)

    it("continues a blockquote after a leader without a space", function()
      h.set_buf({ ">one" })
      h.set_cursor(1, 3)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ ">one", ">two" }, h.get_buf())
    end)

    it("keeps trailing spaces at end of a quoted line", function()
      h.set_buf({ "> one  " })
      h.set_cursor(1, 6)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> one  ", "> two" }, h.get_buf())
    end)

    it("removes an empty blockquote leader instead of continuing it", function()
      h.set_buf({ "> one", "> " })
      h.set_cursor(2, 1)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "> one", "" }, h.get_buf())
    end)

    it("treats a split inside the quote leader as a plain newline", function()
      h.set_buf({ "> one" })
      h.set_cursor(1, 0)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "", "> one" }, h.get_buf())
    end)
  end)

  describe("list inside a blockquote", function()
    it("continues an indented quoted bullet without doubling the indent", function()
      h.set_buf({ "  > - one" })
      h.set_cursor(1, 8)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "  > - one", "  > - two" }, h.get_buf())
    end)

    it("continues a quoted bullet at end of line", function()
      h.set_buf({ "> - one" })
      h.set_cursor(1, 6)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> - one", "> - two" }, h.get_buf())
    end)

    it("continues a quoted bullet when splitting mid-line", function()
      h.set_buf({ "> - one two" })
      h.set_cursor(1, 7)
      h.feed("i<CR>")
      h.ensure_normal()
      assert.are.same({ "> - one", "> - two" }, h.get_buf())
    end)

    it("keeps the body indent of a nested quoted bullet", function()
      h.set_buf({ "> - parent", ">     - one" })
      h.set_cursor(2, 10)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> - parent", ">     - one", ">     - two" }, h.get_buf())
    end)

    it("numbers a quoted ordered list", function()
      h.set_buf({ "> 1. one", "> 2. two" })
      h.set_cursor(1, 7)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "> 1. one", "> 2. x", "> 3. two" }, h.get_buf())
    end)

    it("renumbers only the quoted list", function()
      h.set_buf({ "1. outside", "", "> 5. one", "> 8. two" })
      h.set_cursor(3, 7)
      h.feed("a<CR>x")
      h.ensure_normal()
      assert.are.same({ "1. outside", "", "> 1. one", "> 2. x", "> 3. two" }, h.get_buf())
    end)

    it("continues a quoted checkbox item", function()
      h.set_buf({ "> - [x] one" })
      h.set_cursor(1, 10)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> - [x] one", "> - [ ] two" }, h.get_buf())
    end)

    it("nests a quoted item after a trailing colon", function()
      h.set_buf({ "> - head:" })
      h.set_cursor(1, 8)
      h.feed("a<CR>tail")
      h.ensure_normal()
      assert.are.same({ "> - head:", ">     - tail" }, h.get_buf())
    end)

    it("drops an empty quoted bullet but keeps the quote", function()
      h.set_buf({ "> - one", "> - " })
      h.set_cursor(2, 3)
      h.feed("a<CR>")
      h.ensure_normal()
      assert.are.same({ "> - one", "> " }, h.get_buf())
    end)

    it("continues a bullet at nested quote depth", function()
      h.set_buf({ "> > - one" })
      h.set_cursor(1, 8)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> > - one", "> > - two" }, h.get_buf())
    end)

    it("stops the list block at a quote depth change", function()
      h.set_buf({ "> > 1. deep", "> 1. one" })
      h.set_cursor(2, 7)
      h.feed("a<CR>two")
      h.ensure_normal()
      assert.are.same({ "> > 1. deep", "> 1. one", "> 2. two" }, h.get_buf())
    end)
  end)

  describe("o", function()
    it("continues the list", function()
      h.set_buf({ "- one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "- one", "- two" }, h.get_buf())
    end)

    it("numbers the new item", function()
      h.set_buf({ "1. one", "2. two" })
      h.set_cursor(1)
      h.feed("ox")
      h.ensure_normal()
      assert.are.same({ "1. one", "2. x", "3. two" }, h.get_buf())
    end)

    it("clears an empty item", function()
      h.set_buf({ "- one", "- " })
      h.set_cursor(2)
      h.feed("o")
      h.ensure_normal()
      assert.are.same({ "- one", "" }, h.get_buf())
    end)

    it("continues a quoted list and a quoted paragraph", function()
      h.set_buf({ "> - one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "> - one", "> - two" }, h.get_buf())
      h.set_buf({ "> > one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "> > one", "> > two" }, h.get_buf())
    end)

    it("is a plain new line on a paragraph", function()
      h.set_buf({ "one" })
      h.set_cursor(1)
      h.feed("otwo")
      h.ensure_normal()
      assert.are.same({ "one", "two" }, h.get_buf())
    end)
  end)

  describe("dot repeat", function()
    it("repeats cw<CR> on a middle word", function()
      h.set_buf({ "- aaa bbb ccc", "- ddd eee fff" })
      h.set_cursor(1, 6)
      h.feed("cw<CR><Esc>")
      h.set_cursor(3, 6)
      h.feed(".")
      assert.are.same({ "- aaa", "- ccc", "- ddd", "- fff" }, h.get_buf())
    end)

    it("repeats cw<CR> on the last word", function()
      h.set_buf({ "- aaa bbb", "- ccc ddd" })
      h.set_cursor(1, 6)
      h.feed("cw<CR><Esc>")
      h.set_cursor(3, 6)
      h.feed(".")
      -- cw leaves the space before the word; at end of line it stays (hard break rule)
      assert.are.same({ "- aaa ", "- ", "- ccc ", "- " }, h.get_buf())
    end)

    it("repeats on a quoted paragraph", function()
      h.set_buf({ "> aaa bbb ccc", "> ddd eee fff" })
      h.set_cursor(1, 6)
      h.feed("cw<CR><Esc>")
      h.set_cursor(3, 6)
      h.feed(".")
      assert.are.same({ "> aaa", "> ccc", "> ddd", "> fff" }, h.get_buf())
    end)

    it("repeats on a quoted item", function()
      h.set_buf({ "> - aaa bbb ccc", "> - ddd eee fff" })
      h.set_cursor(1, 8)
      h.feed("cw<CR><Esc>")
      h.set_cursor(3, 8)
      h.feed(".")
      assert.are.same({ "> - aaa", "> - ccc", "> - ddd", "> - fff" }, h.get_buf())
    end)

    it("repeats on a nested item", function()
      h.set_buf({ "    - aaa bbb ccc", "    - ddd eee fff" })
      h.set_cursor(1, 10)
      h.feed("cw<CR><Esc>")
      h.set_cursor(3, 10)
      h.feed(".")
      assert.are.same({ "    - aaa", "    - ccc", "    - ddd", "    - fff" }, h.get_buf())
    end)

    it("replays the number literally on a numbered item", function()
      h.set_buf({ "1. aaa bbb", "", "1. ccc ddd" })
      h.set_cursor(1, 7)
      h.feed("cw<CR><Esc>")
      h.set_cursor(4, 7)
      h.feed(".")
      assert.are.same({ "1. aaa ", "2. ", "", "1. ccc ", "2. " }, h.get_buf())
    end)

    it("repeats A<CR>text", function()
